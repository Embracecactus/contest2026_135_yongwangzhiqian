"""Write src/speech.js: per-frame loudness of every on-screen line, so 周屿's
mouth and Shaniu's "speaking" pulse follow the actual audio placed by the edit.

Start times are film time (after the edit's warp). Levels are RMS per 1/30 s frame, quantised 0..9. Narration (N*) is voice-over
and moves no mouth.

Usage: python3 tools/build_speech_js.py
"""
import json
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]
FPS = 30


sys.path.insert(0, str(Path(__file__).resolve().parent))
from editlib import load_edit, film_from_story  # noqa: E402


def envelope(path, gain_db=0.0):
    x, sr = sf.read(path, always_2d=False)
    if x.ndim > 1:
        x = x.mean(axis=1)
    hop = sr // FPS
    n = len(x) // hop
    rms = np.sqrt(np.mean(x[: n * hop].reshape(n, hop) ** 2, axis=1) + 1e-12)
    d = 20 * np.log10(rms)
    top = np.percentile(d, 97)                          # per line: loudest syllables → 9
    lv = np.clip((d - (top - 26)) / 26, 0, 1) * min(1.0, 10 ** (gain_db / 40))
    q = np.round(lv * 9).astype(int)
    return "".join(str(v) for v in q)


def main():
    E = load_edit()
    gg = ROOT / "audio/voice/zhouyu/directed"
    sh = ROOT / "audio/voice/shaniu"
    him, her = [], []
    for line in E["lines"]:
        i = line["id"]
        if i.startswith("D"):
            him.append([round(film_from_story(E, line["at"]), 3), envelope(gg / f"{i}.wav", line.get("gain_db", 0) * 0.3), i])
        elif i.startswith("S") or i == "W":
            her.append([round(film_from_story(E, line["at"]), 3), envelope(sh / f"{i}.wav"), i])
    out = ROOT / "src/speech.js"
    body = json.dumps({"fps": FPS, "him": him, "her": her}, ensure_ascii=False)
    out.write_text("// SPDX-License-Identifier: Apache-2.0\n// Generated by tools/build_speech_js.py from the edit and the voice files. Do not edit.\n"
                   f"export const SPEECH = {body};\n", encoding="utf-8")
    print(out, len(him), "him lines,", len(her), "her lines")


if __name__ == "__main__":
    main()

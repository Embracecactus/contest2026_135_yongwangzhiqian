#!/usr/bin/env python3
"""Materialize a safe, entity-local BK7258 source snapshot.

The BK7258 executor has to build against a private view of the source tree.
This module owns only that source-view preparation step.  It deliberately
does not invoke a compiler, a packer, a signer, or hardware tooling.

The source checkout is copied by walking the filesystem rather than by using
``git archive``.  That is important for the contest tree: a dirty board
change and an ignored-but-required OpenAMP source file are both build inputs.
Only relative symlinks whose final target is inside the snapshot may survive.
Every copied regular file is a new inode and the completed tree is made
read-only.  Bootloader outputs are intentionally excluded; a role staging
step must copy the bootloader inputs/outputs to a separate writable area.
"""


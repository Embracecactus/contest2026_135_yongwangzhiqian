def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--workspace-root", "--workspace", dest="workspace_root", required=True,
        type=Path, help="workspace containing the eight required source roots")
    parser.add_argument(
        "--destination", "--dest", dest="destination", required=False,
        type=Path, help="new destination outside the workspace")
    parser.add_argument(
        "--symlink-preflight", action="store_true",
        help="audit source symlinks only; do not create a snapshot")
    return parser


def main(argv: Iterable[str] | None = None) -> int:
    args = _build_parser().parse_args(list(argv) if argv is not None else None)
    try:
        if args.symlink_preflight:
            result = audit_source_symlinks(args.workspace_root)
        else:
            if args.destination is None:
                _build_parser().error(
                    "--destination is required unless --symlink-preflight is used")
            manifest = snapshot_workspace(args.workspace_root, args.destination)
    except SnapshotError as error:
        print(f"bk7258-source-snapshot: ERROR: {error}", file=sys.stderr)
        return 2
    print(json.dumps(
        result if args.symlink_preflight else manifest,
        ensure_ascii=False,
        sort_keys=True,
        indent=2,
    ))
    return 0



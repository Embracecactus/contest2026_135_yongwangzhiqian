int bk7258_boot_n17_verify_signature(
  uint32_t key_id, const uint8_t signed_data[448],
  const uint8_t signature[64])
{
  struct boot_sha256_context_s sha256;
  uint8_t digest[32];
  uint8_t public_key[BK7258_BOOT_N17_P256_COMPRESSED_PUBLIC_KEY_SIZE];

  if (signed_data == NULL || signature == NULL ||
      bk7258_ota_n17_lookup_public_key(key_id, public_key) < 0)
    {
      return -1;
    }

  boot_sha256_init(&sha256);
  boot_sha256_update(&sha256, signed_data, 448u);
  boot_sha256_final(&sha256, digest);

  /* N17's fixed-width signature is exactly the r || s representation that
   * NuttX's upstream secp256r1 verifier accepts.  The Manifest parser has
   * already rejected non-canonical or high-S encodings before this call.
   */

  return ecdsa_verify(public_key, digest, signature) == 1 ? 0 : -1;
}

